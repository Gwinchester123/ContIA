BEGIN;
LOCK TABLE public.vendas IN SHARE ROW EXCLUSIVE MODE;

DO $$
DECLARE
    vendas_count BIGINT;
    divergencias_count BIGINT;
BEGIN
    IF to_regclass('public.funcionarios') IS NOT NULL THEN
        RAISE EXCEPTION 'Validação interrompida: public.funcionarios já existe.';
    END IF;
    IF to_regclass('public.venda_itens') IS NOT NULL THEN
        RAISE EXCEPTION 'Validação interrompida: public.venda_itens já existe.';
    END IF;
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'vendas'
          AND column_name IN ('proprietario_responsavel_id', 'funcionario_responsavel_id')
    ) THEN
        RAISE EXCEPTION 'Validação interrompida: colunas de responsável já existem.';
    END IF;

    SELECT COUNT(*) INTO vendas_count FROM public.vendas;
    IF vendas_count <> 18 THEN
        RAISE EXCEPTION 'Validação interrompida: esperado 18 vendas, encontrado %.', vendas_count;
    END IF;

    SELECT COUNT(*) INTO divergencias_count
    FROM public.vendas
    WHERE total <> quantidade * valor_unitario;
    IF divergencias_count <> 0 THEN
        RAISE EXCEPTION 'Validação interrompida: % vendas têm total divergente.', divergencias_count;
    END IF;
END $$;

CREATE TABLE public.funcionarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    perfil VARCHAR(20) NOT NULL,
    ativo BOOLEAN NOT NULL,
    estabelecimento_id BIGINT NOT NULL REFERENCES public.estabelecimentos(id)
);
CREATE INDEX idx_funcionarios_estabelecimento_id
    ON public.funcionarios(estabelecimento_id);

CREATE TABLE public.venda_itens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venda_id BIGINT NOT NULL REFERENCES public.vendas(id),
    produto VARCHAR(100) NOT NULL,
    quantidade INTEGER NOT NULL,
    valor_unitario NUMERIC(10, 2) NOT NULL,
    subtotal NUMERIC(10, 2) NOT NULL,
    ordem INTEGER NOT NULL
);
CREATE INDEX idx_venda_itens_venda_id ON public.venda_itens(venda_id);
CREATE INDEX idx_venda_itens_produto ON public.venda_itens(produto);

ALTER TABLE public.vendas
    ADD COLUMN proprietario_responsavel_id BIGINT NULL
        REFERENCES public.proprietarios(id),
    ADD COLUMN funcionario_responsavel_id BIGINT NULL
        REFERENCES public.funcionarios(id);
CREATE INDEX idx_vendas_proprietario_responsavel_id
    ON public.vendas(proprietario_responsavel_id);
CREATE INDEX idx_vendas_funcionario_responsavel_id
    ON public.vendas(funcionario_responsavel_id);

INSERT INTO public.venda_itens
    (venda_id, produto, quantidade, valor_unitario, subtotal, ordem)
SELECT v.id, v.produto, v.quantidade, v.valor_unitario, v.total, 0
FROM public.vendas v
WHERE NOT EXISTS (
    SELECT 1 FROM public.venda_itens i WHERE i.venda_id = v.id
);

DO $$
DECLARE
    venda_item_count BIGINT;
    vendas_sem_item BIGINT;
    itens_invalidos BIGINT;
    responsaveis_atribuidos BIGINT;
BEGIN
    SELECT COUNT(*) INTO venda_item_count FROM public.venda_itens;
    IF venda_item_count <> 18 THEN
        RAISE EXCEPTION 'Validação interrompida: esperado 18 itens históricos, encontrado %.', venda_item_count;
    END IF;

    SELECT COUNT(*) INTO vendas_sem_item
    FROM public.vendas v
    WHERE NOT EXISTS (SELECT 1 FROM public.venda_itens i WHERE i.venda_id = v.id);
    IF vendas_sem_item <> 0 THEN
        RAISE EXCEPTION 'Validação interrompida: % vendas continuam sem item.', vendas_sem_item;
    END IF;

    SELECT COUNT(*) INTO itens_invalidos
    FROM public.vendas v
    JOIN public.venda_itens i ON i.venda_id = v.id
    WHERE i.produto <> v.produto
       OR i.quantidade <> v.quantidade
       OR i.valor_unitario <> v.valor_unitario
       OR i.subtotal <> v.total
       OR i.ordem <> 0;
    IF itens_invalidos <> 0 THEN
        RAISE EXCEPTION 'Validação interrompida: % itens não correspondem aos dados históricos.', itens_invalidos;
    END IF;

    SELECT COUNT(*) INTO responsaveis_atribuidos
    FROM public.vendas
    WHERE proprietario_responsavel_id IS NOT NULL
       OR funcionario_responsavel_id IS NOT NULL;
    IF responsaveis_atribuidos <> 0 THEN
        RAISE EXCEPTION 'Validação interrompida: vendas históricas receberam responsável indevidamente.';
    END IF;
END $$;

COMMIT;
